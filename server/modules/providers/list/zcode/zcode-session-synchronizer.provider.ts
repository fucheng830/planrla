import fsSync from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { readFile, readdir } from 'node:fs/promises';

import { sessionsDb } from '@/modules/database/index.js';
import type { IProviderSessionSynchronizer } from '@/shared/interfaces.js';
import type { AnyRecord } from '@/shared/types.js';
import { getZcodeCliHome } from '@/modules/providers/list/zcode/zcode-auth.provider.js';
import {
  normalizeSessionName,
  readJsonRecord,
  readObjectRecord,
  readOptionalString,
} from '@/shared/utils.js';

const FALLBACK_TITLE = 'Untitled ZCode Session';

/**
 * Wrapper blocks the CLI injects into user-role messages (context preamble,
 * task notifications, ambient UI state, fork provenance). A message
 * consisting ONLY of these blocks is not a human prompt and must not become
 * the session title. Open tags may carry attributes (`<system-reminder foo>`).
 */
const INJECTED_WRAPPERS: ReadonlyArray<{ openTag: string; closeTag: string }> = [
  { openTag: 'system-reminder', closeTag: 'system-reminder' },
  { openTag: 'task-notification', closeTag: 'task-notification' },
  { openTag: 'in-app-browser-context', closeTag: 'in-app-browser-context' },
  { openTag: 'command-name', closeTag: 'command-message' },
];

/** Marker lines injected instead of wrappers (fork provenance, etc.). */
const INJECTED_LINE_PREFIXES = [
  'This session was forked from',
  'Caveat: The messages below were generated by the user',
  'parentSessionId:',
  'targetMessageId:',
];

/**
 * Removes injected wrapper blocks from a message text. Returns the remaining
 * human text, or an empty string when the message is entirely injected
 * content (→ caller should try the next user message).
 */
function stripInjectedBlocks(text: string): string {
  let remaining = text;
  for (const { openTag, closeTag } of INJECTED_WRAPPERS) {
    const pattern = new RegExp(
      `<${openTag}[^>]*>[\\s\\S]*?</${closeTag}\\s*>`,
      'g',
    );
    remaining = remaining.replace(pattern, '');
  }
  const lines = remaining
    .split('\n')
    .filter((line) => !INJECTED_LINE_PREFIXES.some((prefix) => line.trim().startsWith(prefix)));
  return lines.join('\n').trim();
}

/** True when a stored title was derived from injected content (repairable). */
function isInjectedTitle(name: string | undefined | null): boolean {
  const value = (name ?? '').trim();
  if (!value) return true;
  return INJECTED_WRAPPERS.some(({ openTag }) => value.startsWith(`<${openTag}`));
}

/** Test hooks (pure functions; no DB/filesystem involvement). */
export const __testing__ = {
  stripInjectedBlocks,
  isInjectedTitle,
};

type ParsedSession = {
  sessionId: string;
  projectPath: string;
  sessionName?: string;
  createdAt?: string;
  updatedAt?: string;
  transcriptPath: string | null;
};

/**
 * Session indexer for ZCode. ZCode stores per-turn transcripts as
 * ~/.zcode/cli/rollout/model-io-sess_<id>.jsonl (one `model_io` object per
 * line). There is no separate per-session metadata index file; the first user
 * prompt of the first turn is used as the session title, and the project path
 * falls back to the user's home (ZCode does not persist a per-session cwd in
 * the rollout — that lives in its sqlite DB, which we do not read here yet).
 */
export class ZcodeSessionSynchronizer implements IProviderSessionSynchronizer {
  private readonly provider = 'zcode' as const;

  private rolloutDir(): string {
    return path.join(getZcodeCliHome(), 'rollout');
  }

  /**
   * Full scan of the rollout directory. Used by the watcher's initial sync.
   */
  async synchronize(since?: Date): Promise<number> {
    let files: string[];
    try {
      files = await readdir(this.rolloutDir());
    } catch {
      return 0;
    }

    let processed = 0;
    for (const file of files) {
      if (!file.startsWith('model-io-sess_') || !file.endsWith('.jsonl')) continue;
      const sessionId = file.replace(/^model-io-/, '').replace(/\.jsonl$/, '');
      if (!sessionId) continue;

      const parsed = await this.parseFromRollout(sessionId);
      if (!parsed) continue;

      if (since && parsed.updatedAt) {
        const updatedAt = Date.parse(parsed.updatedAt);
        if (Number.isFinite(updatedAt) && updatedAt < since.getTime()) continue;
      }

      this.upsertSession(parsed);
      processed += 1;
    }
    return processed;
  }

  /**
   * Handles watcher changes under ~/.zcode/cli/rollout. Only
   * `model-io-sess_<id>.jsonl` files carry session facts.
   */
  async synchronizeFile(filePath: string): Promise<string | null> {
    const basename = path.basename(filePath);
    if (!basename.startsWith('model-io-sess_') || !basename.endsWith('.jsonl')) {
      return null;
    }
    const sessionId = basename.replace(/^model-io-/, '').replace(/\.jsonl$/, '');
    if (!sessionId) return null;

    const parsed = await this.parseFromRollout(sessionId);
    if (!parsed) return null;
    return this.upsertSession(parsed);
  }

  /**
   * Reads the first turn of a rollout file to derive a title (first user
   * prompt) and timestamps. Subsequent turns only contribute to history
   * (handled by the sessions provider's fetchHistory).
   */
  private async parseFromRollout(sessionId: string): Promise<ParsedSession | null> {
    const transcriptPath = path.join(this.rolloutDir(), `model-io-${sessionId}.jsonl`);
    if (!fsSync.existsSync(transcriptPath)) return null;

    let content: string;
    try {
      content = await readFile(transcriptPath, 'utf8');
    } catch {
      return null;
    }

    let firstPrompt: string | undefined;
    let createdAt: string | undefined;
    let updatedAt: string | undefined;

    for (const line of content.split('\n')) {
      const trimmed = line.trim();
      if (!trimmed) continue;
      const entry = readJsonRecord(trimmed);
      if (!entry) continue;

      const startedAt = readOptionalString(entry.startedAt);
      const completedAt = readOptionalString(entry.completedAt);
      if (startedAt && !createdAt) createdAt = startedAt;
      if (completedAt) updatedAt = completedAt;

      if (!firstPrompt) {
        // Message arrays live at request.messages on current CLI builds;
        // request.body.messages is the older layout — read both.
        const request = readObjectRecord(entry.request);
        const messageSources = [
          Array.isArray(request?.messages) ? request.messages : null,
          Array.isArray(readObjectRecord(request?.body)?.messages) ? (request!.body as AnyRecord).messages : null,
        ];
        for (const messages of messageSources) {
          if (!messages || firstPrompt) break;
          for (const raw of messages) {
            const msg = readObjectRecord(raw);
            if (readOptionalString(msg?.role) !== 'user') continue;
            const text = typeof msg?.content === 'string'
              ? msg.content
              : this.extractContentText(msg?.content);
            if (!text?.trim()) continue;
            // Skip injected preambles (system-reminder context, task
            // notifications, fork provenance) — keep scanning for the first
            // message with real human text.
            const humanText = stripInjectedBlocks(text);
            if (humanText) {
              firstPrompt = humanText;
              break;
            }
          }
        }
      }
    }

    return {
      sessionId,
      // ZCode does not persist a per-session cwd in the rollout; fall back to
      // home so the session still lands in a valid project bucket.
      projectPath: os.homedir(),
      sessionName: normalizeSessionName(firstPrompt, FALLBACK_TITLE),
      createdAt,
      updatedAt,
      transcriptPath,
    };
  }

  private extractContentText(content: unknown): string | undefined {
    if (typeof content === 'string') return content;
    if (!Array.isArray(content)) return undefined;
    for (const block of content) {
      const record = readObjectRecord(block);
      if (readOptionalString(record?.type) === 'text') {
        const text = readOptionalString(record?.text);
        if (text?.trim()) return text;
      }
    }
    return undefined;
  }

  private upsertSession(parsed: ParsedSession): string | null {
    const pendingAppSession = sessionsDb.getSessionByProviderSessionId(parsed.sessionId)
      ?? sessionsDb.getSessionById(parsed.sessionId)
      ?? sessionsDb.findLatestPendingAppSession(this.provider, parsed.projectPath);
    if (pendingAppSession && !pendingAppSession.provider_session_id) {
      sessionsDb.assignProviderSessionId(pendingAppSession.session_id, parsed.sessionId);
    }

    const existingSession = sessionsDb.getSessionByProviderSessionId(parsed.sessionId)
      ?? sessionsDb.getSessionById(parsed.sessionId);
    const existingName = existingSession?.custom_name;
    // Keep user-renamed titles; replace fallbacks AND titles that were derived
    // from injected preambles (<system-reminder>…) so old bad names repair on
    // the next sync.
    const nextName = existingName && existingName !== FALLBACK_TITLE && !isInjectedTitle(existingName)
      ? existingName
      : parsed.sessionName;

    return sessionsDb.createSession(
      parsed.sessionId,
      this.provider,
      parsed.projectPath,
      nextName,
      parsed.createdAt,
      parsed.updatedAt ?? parsed.createdAt,
      parsed.transcriptPath,
    );
  }
}
