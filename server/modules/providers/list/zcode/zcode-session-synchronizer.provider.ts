const FALLBACK_TITLE = 'Untitled ZCode Session';

/**
 * Wrapper blocks the CLI injects into user-role messages (context preamble,
 * task notifications, ambient UI state, fork provenance). A message
 * consisting ONLY of these blocks is not a human prompt and must not become
 * the session title. Open tags may carry attributes (`<system-reminder foo>`).
 */
const INJECTED_WRAPPERS: ReadonlyArray<{ openTag: string; closeTag: string }> = [
  { openTag: 'system-reminder', closeTag: 'system-reminder' },
  { openTag: 'task-notification', closeTag: 'task-notification' },
  { openTag: 'in-app-browser-context', closeTag: 'in-app-browser-context' },
  { openTag: 'command-name', closeTag: 'command-message' },
];

/** Marker lines injected instead of wrappers (fork provenance, etc.). */
const INJECTED_LINE_PREFIXES = [
  'This session was forked from',
  'Caveat: The messages below were generated by the user',
  'parentSessionId:',
  'targetMessageId:',
];

/**
 * Removes injected wrapper blocks from a message text. Returns the remaining
 * human text, or an empty string when the message is entirely injected
 * content (→ caller should try the next user message).
 */
function stripInjectedBlocks(text: string): string {
  let remaining = text;
  for (const { openTag, closeTag } of INJECTED_WRAPPERS) {
    const pattern = new RegExp(
      `<${openTag}[^>]*>[\\s\\S]*?</${closeTag}\\s*>`,
      'g',
    );
    remaining = remaining.replace(pattern, '');
  }
  const lines = remaining
    .split('\n')
    .filter((line) => !INJECTED_LINE_PREFIXES.some((prefix) => line.trim().startsWith(prefix)));
  return lines.join('\n').trim();
}

/** True when a stored title was derived from injected content (repairable). */
function isInjectedTitle(name: string | undefined | null): boolean {
  const value = (name ?? '').trim();
  if (!value) return true;
  return INJECTED_WRAPPERS.some(({ openTag }) => value.startsWith(`<${openTag}`));
}

